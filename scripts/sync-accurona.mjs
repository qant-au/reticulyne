// Vendor Accurona's shared packages (qant-au/accurona) into src/vendor/.
//
//   node scripts/sync-accurona.mjs [path-to-accurona-checkout]
//
// Copies packages/<name>/dist/ into src/vendor/accurona-<name>/ (ui, core)
// and records the source commit, then the isometric drawings the catalogue
// cross-references into src/vendor/accurona-iso/. Defaults to ../accurona
// next to this repo.
// Run `npm run build` in the accurona checkout first.
import { execFileSync } from 'node:child_process';
import {
  cpSync,
  existsSync,
  mkdirSync,
  readFileSync,
  rmSync,
  writeFileSync
} from 'node:fs';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const source = resolve(process.argv[2] ?? resolve(root, '../accurona'));
const packages = [
  { name: 'ui', label: 'shared UI' },
  { name: 'core', label: 'core (the scene format)' }
];

for (const { name } of packages) {
  const dist = resolve(source, `packages/${name}/dist`);
  if (!existsSync(resolve(dist, 'index.js'))) {
    console.error(`No ${dist}/index.js. Run \`npm run build\` in ${source}.`);
    process.exit(1);
  }
}

const git = (...args) =>
  execFileSync('git', ['-C', source, ...args], { encoding: 'utf8' }).trim();
const commit = git('rev-parse', '--short', 'HEAD');
const dirty = git('status', '--porcelain') !== '';

for (const { name, label } of packages) {
  const target = resolve(root, `src/vendor/accurona-${name}`);
  rmSync(target, { recursive: true, force: true });
  cpSync(resolve(source, `packages/${name}/dist`), target, { recursive: true });
  writeFileSync(
    resolve(target, 'SOURCE.md'),
    `# Vendored ${label}\n\n\`@accurona/${name}\`, built by [qant-au/accurona](https://github.com/qant-au/accurona) at \`${commit}\`${dirty ? ' (with uncommitted changes)' : ''}.\nDo not edit these files: change packages/${name} in that repo and re-run\n\`node scripts/sync-accurona.mjs\`.\n`
  );
}

// The isometric drawings of the elements the catalogue cross-references
// (`twin('<element id>')` in src/catalogue/items.ts), from the library's
// dist/iso/, as one module: element id -> { name, svg }. Only those, so
// the bundle does not carry the whole library.
const items = readFileSync(resolve(root, 'src/catalogue/items.ts'), 'utf8');
const twins = [
  ...new Set([...items.matchAll(/\btwin\('([a-z0-9-]+)'\)/g)].map((m) => m[1]))
].sort();
const manifest = JSON.parse(
  readFileSync(resolve(source, 'dist/manifest.json'), 'utf8')
);
const names = new Map(manifest.elements.map((el) => [el.id, el.name]));
const drawings = {};
for (const id of twins) {
  const file = resolve(source, `dist/iso/${id}.svg`);
  if (!names.has(id) || !existsSync(file)) {
    console.error(`No element "${id}" with an isometric view in ${source}/dist.`);
    process.exit(1);
  }
  drawings[id] = { name: names.get(id), svg: readFileSync(file, 'utf8').trim() };
}
const isoTarget = resolve(root, 'src/vendor/accurona-iso');
rmSync(isoTarget, { recursive: true, force: true });
mkdirSync(isoTarget, { recursive: true });
writeFileSync(
  resolve(isoTarget, 'index.js'),
  `// Generated by scripts/sync-accurona.mjs. Do not edit.\nexport const ISO_DRAWINGS = ${JSON.stringify(drawings, null, 2)};\n`
);
writeFileSync(
  resolve(isoTarget, 'index.d.ts'),
  'export declare const ISO_DRAWINGS: Record<string, { name: string; svg: string }>;\n'
);
writeFileSync(
  resolve(isoTarget, 'SOURCE.md'),
  `# Vendored isometric drawings\n\nThe isometric view (\`dist/iso/<id>.svg\` of \`@accurona/elements\`) of each element a\ncatalogue item cross-references, built by [qant-au/accurona](https://github.com/qant-au/accurona) at \`${commit}\`${dirty ? ' (with uncommitted changes)' : ''}.\nDo not edit these files: re-run \`node scripts/sync-accurona.mjs\`.\n`
);

console.log(
  `Synced ${packages.map((p) => `@accurona/${p.name}`).join(', ')} and ${twins.length} isometric drawings @ ${commit}${dirty ? '+dirty' : ''} → src/vendor/`
);
